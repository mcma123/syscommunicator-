import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url);
const inputs = {
  receiptCrest: "public/logo.png",
  receiptFont: "node_modules/@expo-google-fonts/open-sans/400Regular/OpenSans_400Regular.ttf",
  receiptBoldFont: "node_modules/@expo-google-fonts/open-sans/700Bold/OpenSans_700Bold.ttf",
};
const license = await readFile(
  new URL("node_modules/@expo-google-fonts/open-sans/LICENSE_FONT", root),
  "utf8",
);
let source = "// Generated by scripts/prepare-receipt-assets.mjs. Do not edit.\n";
source += `/* Open Sans font license (source: @expo-google-fonts/open-sans):\n${license.replaceAll("*/", "* /")}\n*/\n`;
for (const [name, path] of Object.entries(inputs)) {
  const bytes = await readFile(new URL(path, root));
  source += `// ${path}; sha256: ${createHash("sha256").update(bytes).digest("hex")}\n`;
  source += `export const ${name} = "${bytes.toString("base64")}";\n`;
}
await writeFile(new URL("packages/backend/convex/receiptAssets.ts", root), source);
console.log("Prepared receipt crest and licensed Open Sans fonts.");
